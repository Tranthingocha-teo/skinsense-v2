// Reads tokens.json, fails on any text pair below WCAG AA (4.5:1) in either theme,
// then writes dist/web.css (hex, shadcn names, Tailwind v4) and dist/nativewind.css
// (HSL triplets, NativeWind 4 / Tailwind 3 `hsl(var(--x))`, dark via `.dark:root`).
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const here = (p) => new URL(p, import.meta.url);
const T = JSON.parse(readFileSync(here('./tokens.json'), 'utf8'));

const channels = (h) => [1, 3, 5].map((i) => parseInt(h.slice(i, i + 2), 16) / 255);
const lum = (h) =>
  channels(h)
    .map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4))
    .reduce((sum, c, i) => sum + c * [0.2126, 0.7152, 0.0722][i], 0);
const ratio = (a, b) => {
  const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p);
  return (x + 0.05) / (y + 0.05);
};
const hsl = (h) => {
  const [r, g, b] = channels(h);
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2, d = max - min;
  const s = d === 0 ? 0 : d / (1 - Math.abs(2 * l - 1));
  const hue = d === 0 ? 0 : max === r ? ((g - b) / d) % 6 : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  const f = (n) => Math.round(n * 10) / 10;
  return `${f((hue * 60 + 360) % 360)} ${f(s * 100)}% ${f(l * 100)}%`;
};

// Text-on-background pairs that must stay readable.
const PAIRS = [
  ['fg', 'bg'], ['fg', 'surface'], ['fg', 'surface-2'], ['muted', 'bg'], ['muted', 'surface'], ['muted', 'surface-2'],
  ['on-accent', 'accent'], ['on-accent', 'good'], ['good', 'surface'], ['good', 'bg'], ['danger', 'surface'], ['danger', 'bg'], ['on-accent', 'danger'],
];
// shadcn variable name -> C3 role
const ROLES = {
  background: 'bg', foreground: 'fg', card: 'surface', 'card-foreground': 'fg', popover: 'surface', 'popover-foreground': 'fg',
  primary: 'accent', 'primary-foreground': 'on-accent', secondary: 'surface-2', 'secondary-foreground': 'fg',
  muted: 'surface-2', 'muted-foreground': 'muted', accent: 'surface-2', 'accent-foreground': 'fg',
  destructive: 'danger', 'destructive-foreground': 'on-accent', success: 'good', border: 'line', input: 'line', ring: 'fg',
  'surface-2': 'surface-2', 'photo-a': 'photo-a', 'photo-b': 'photo-b', 'photo-c': 'photo-c',
  // Aliases for utilities the apps already use (no brand hue: highlights are surface-2, charts are fg/good/muted).
  'primary-soft': 'surface-2', 'chart-1': 'fg', 'chart-2': 'good', 'chart-3': 'muted', 'chart-4': 'line', 'chart-5': 'danger',
  sidebar: 'bg', 'sidebar-foreground': 'fg', 'sidebar-primary': 'accent', 'sidebar-primary-foreground': 'on-accent',
  'sidebar-accent': 'surface-2', 'sidebar-accent-foreground': 'fg', 'sidebar-border': 'line', 'sidebar-ring': 'fg',
};

let failures = 0;
for (const theme of ['dark', 'light']) {
  for (const [a, b] of PAIRS) {
    const r = ratio(T.color[theme][a], T.color[theme][b]);
    if (r < 4.5) {
      failures++;
      console.error(`AA fail ${theme} ${a} on ${b}: ${r.toFixed(2)}`);
    }
  }
}
if (failures) process.exit(1);

const block = (theme, format) =>
  Object.entries(ROLES).map(([name, role]) => `  --${name}: ${format(T.color[theme][role])};`).join('\n');
const radius = Object.entries(T.radius).map(([k, v]) => `  --radius-${k}: ${v}px;`).join('\n');
const header = '/* Generated by packages/tokens/build.mjs from tokens.json. Do not edit. */';

mkdirSync(here('./dist/'), { recursive: true });
writeFileSync(here('./dist/web.css'), `${header}\n:root {\n${block('light', (h) => h)}\n${radius}\n}\n\n.dark {\n${block('dark', (h) => h)}\n}\n`);
writeFileSync(
  here('./dist/nativewind.css'),
  `${header}\n@layer base {\n  :root {\n${block('light', hsl).replaceAll('\n  ', '\n    ').replace(/^  /, '    ')}\n  }\n  .dark:root {\n${block('dark', hsl).replaceAll('\n  ', '\n    ').replace(/^  /, '    ')}\n  }\n}\n`,
);
console.log(`tokens: ${PAIRS.length * 2} contrast pairs pass, wrote dist/web.css and dist/nativewind.css`);
